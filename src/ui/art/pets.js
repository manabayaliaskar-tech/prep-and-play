export const PETS = Object.fromEntries(Object.entries(ART).map(([id, art]) => [id, `<g class="pet-art pet-${id}">${art}</g>`]));

const SHADOW = '<ellipse class="pet-shadow" cx="0" cy="0" rx="13" ry="2.2" fill="#000" opacity=".13"/>';

/** Питомец рядом с Препи (справа внизу). */
export function petSvg(id) {
  if (!id) return '';
  if (PETS[id]) return `<g transform="translate(121 147.4) scale(.98)">${SHADOW}<g class="pet pet-${id}">${PETS[id]}</g></g>`;
  const icon = itemById(id)?.icon;
  return icon ? `<g class="pet pet-${id}"><text x="122" y="146" font-size="30" text-anchor="middle">${icon}</text></g>` : '';
}

/** Питомец отдельно — для витрины магазина: viewBox подогнан под рисунок. */
export function petAlone(id) {
  if (!PETS[id]) return '';
  return `<svg class="art-thumb" viewBox="-24 -42 48 46" aria-hidden="true">${SHADOW}${PETS[id]}</svg>`;
}
