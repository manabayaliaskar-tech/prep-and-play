const INK = '#22164f';
const N = (v) => Math.round(v * 10) / 10;

// ---------- Кирпичики ----------
const S = (o, w = 1.3) => ` stroke="${o}" stroke-width="${w}"`;
const E = (cx, cy, rx, ry, f, x = '') => `<ellipse cx="${N(cx)}" cy="${N(cy)}" rx="${N(rx)}" ry="${N(ry)}" fill="${f}"${x}/>`;
const C = (cx, cy, r, f, x = '') => `<circle cx="${N(cx)}" cy="${N(cy)}" r="${N(r)}" fill="${f}"${x}/>`;
const R = (x, y, w, h, rx, f, extra = '') => `<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="${rx}" fill="${f}"${extra}/>`;
const P = (d, f, o, w = 1.3, x = '') => `<path d="${d}" fill="${f}"${o ? S(o, w) : ''}${x}/>`;
const L = (d, o, w = 1.1, x = '') => `<path d="${d}" fill="none"${S(o, w)}${x}/>`;
const e0 = (cx, cy, rx, ry) => `<ellipse cx="${N(cx)}" cy="${N(cy)}" rx="${N(rx)}" ry="${N(ry)}"/>`;
const c0 = (cx, cy, r) => `<circle cx="${N(cx)}" cy="${N(cy)}" r="${N(r)}"/>`;
const G = (attrs, inner) => `<g ${attrs}>${inner}</g>`;
/** Повторить рисунок зеркально относительно x = 0 (уши, лапки, крылья). */
const sym = (m) => `${m}<g transform="scale(-1 1)">${m}</g>`;
/** «Трубка» с контуром: хвосты, щупальца, рога. */
const tube = (d, b, o, w = 2.6, cls = '') => `<g${cls ? ` class="${cls}"` : ''}>${L(d, o, w + 2.4)}${L(d, b, w)}</g>`;
/** Объёмный овал: тень с контуром снизу справа + основной цвет, сдвинутый вверх влево. */
const ball = (cx, cy, rx, ry, [b, s, o]) => E(cx, cy, rx, ry, s, S(o)) + E(cx - 0.6, cy - 0.9, rx - 1.4, ry - 1.6, b);
const hi = (cx, cy, rx = 2.6, ry = 1.5) => E(cx, cy, rx, ry, '#fff', ' opacity=".65"');

/** Пара глаз в стиле Препи. */
function eyes({ y = -20.5, dx = 5, s = 1, x0 = 0, iris = '#4c35d4', look = 0.3 } = {}) {
  const xs = [x0 - dx, x0 + dx];
  const m = (f) => xs.map(f).join('');
  const lx = look * s;
  return `<g class="pet-eyes">${G(`fill="#fff" stroke="${INK}" stroke-width=".6" stroke-opacity=".5"`, m((x) => e0(x, y, 2.5 * s, 2.9 * s)))}${G(
    `fill="${iris}"`,
    m((x) => c0(x + lx, y + 0.5 * s, 1.75 * s)),
  )}${G(`fill="${INK}"`, m((x) => c0(x + lx, y + 0.6 * s, 0.95 * s)))}${G('fill="#fff"', m((x) => c0(x + lx + 0.7 * s, y - 0.3 * s, 0.65 * s)))}</g>`;
}
const blush = (y = -15.6, dx = 9, x0 = 0, r = 2.2) => G('fill="#ff7fa8" opacity=".55"', e0(x0 - dx, y, r, r * 0.6) + e0(x0 + dx, y, r, r * 0.6));
/** Ротик «w» (кошачий). */
const wmouth = (y, o, x0 = 0) => L(`M${N(x0 - 1.9)} ${y} q.95 1.2 1.9 0 q.95 1.2 1.9 0`, o, 1);
const smile = (y, o, w = 1.8, x0 = 0) => L(`M${N(x0 - w)} ${y} q${w} ${N(w * 0.9)} ${N(2 * w)} 0`, o, 1);
/** Открытый ротик с язычком. */
const grin = (y, o, w = 2.4) => P(`M${-w} ${y} Q0 ${N(y + w * 1.6)} ${w} ${y} Z`, '#8a2f4f', o, 0.9) + E(0, y + w * 0.75, w * 0.5, w * 0.3, '#ff8fab');
const feet = ([b, , o], dx = 5, y = -1.8, rx = 3.6, ry = 2.3) => G(`fill="${b}"${S(o, 1.2)}`, e0(-dx, y, rx, ry) + e0(dx, y, rx, ry));
const paws = ([b, s], dx = 5.4, y = -7.4, r = 2.1) => G(`fill="${b}"${S(s, 1)}`, e0(-dx, y, r, r * 0.9) + e0(dx, y, r, r * 0.9));
const body = (p, belly) => ball(0, -8.5, 9.5, 8, p) + (belly ? E(0, -7.2, 5.8, 5, belly) : '');
const head = (p, y = -21, rx = 13.5, ry = 12) => ball(0, y, rx, ry, p) + hi(-6, y - 6.2);

/** Стандартный зверёк-чиби: хвост → тельце → лапки → уши → голова → мордочка. */
function critter(p, { back = '', belly = '#fff6e8', ears = '', mark = '', front = '', eye = {}, mouth, bl = blush() } = {}) {
  return back + body(p, belly) + feet(p) + paws(p) + ears + head(p) + mark + eyes(eye) + bl + (mouth ?? wmouth(-15.8, p[2])) + front;
}

/** Зубчатый круг (грива льва, шерсть овечки, иголки ежа). */
function scallop(cx, cy, rx, ry, n, bump, a0 = 0, a1 = 360, close = true) {
  const pts = [];
  const span = a1 - a0;
  for (let k = 0; k <= n; k++) {
    const a = ((a0 + (span * k) / n) * Math.PI) / 180;
    pts.push([cx + rx * Math.cos(a), cy + ry * Math.sin(a), a]);
  }
  let d = `M${N(pts[0][0])} ${N(pts[0][1])}`;
  for (let k = 1; k < pts.length; k++) {
    const am = (pts[k - 1][2] + pts[k][2]) / 2;
    const qx = cx + (rx + bump) * Math.cos(am);
    const qy = cy + (ry + bump) * Math.sin(am);
    d += ` Q${N(qx)} ${N(qy)} ${N(pts[k][0])} ${N(pts[k][1])}`;
  }
  return close ? `${d} Z` : d;
}
/** Иголки: зигзаг по дуге. */
function spikes(cx, cy, r1, r2, n, a0, a1) {
  let d = '';
  for (let k = 0; k <= 2 * n; k++) {
    const a = ((a0 + ((a1 - a0) * k) / (2 * n)) * Math.PI) / 180;
    const r = k % 2 ? r2 : r1;
    d += `${k ? ' L' : 'M'}${N(cx + r * Math.cos(a))} ${N(cy + r * Math.sin(a))}`;
  }
  return `${d} Z`;
}
/** Горизонтальная полоска внутри эллипса (для пчелы). */
function band(cx, cy, rx, ry, y1, y2) {
  const hx = (y) => N(rx * Math.sqrt(Math.max(0, 1 - ((y - cy) / ry) ** 2)));
  const [a, b] = [hx(y1), hx(y2)];
  return `M${cx - a} ${y1} H${cx + a} A${rx} ${ry} 0 0 1 ${cx + b} ${y2} H${cx - b} A${rx} ${ry} 0 0 1 ${cx - a} ${y1} Z`;
}

