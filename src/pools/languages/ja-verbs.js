/** Формы お/ご-модели: { hon, hum, wrongHon, wrongHum }. */
export function keigoForms(item) {
  if (item.endsWith('する') && !item.includes('|')) {
    const n = item.slice(0, -2);
    return { dict: item, hon: `ご${n}になる`, hum: `ご${n}する`, wrongHon: [`お${n}になる`, `ご${n}にする`, `ご${n}いたす`], wrongHum: [`お${n}する`, `ご${n}にする`, `${n}になる`] };
  }
  const [jp, kana] = item.split('|');
  const stem = conjugate(jp, kana).masu.slice(0, -2);
  return { dict: jp, kana, hon: `お${stem}になる`, hum: `お${stem}する`, wrongHon: [`ご${stem}になる`, `お${jp}になる`, `お${stem}にする`], wrongHum: [`ご${stem}する`, `お${jp}する`, `お${stem}にする`] };
}
