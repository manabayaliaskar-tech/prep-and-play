// Спряжение японских глаголов: годан (う-глаголы), итидан (る-глаголы), する и 来る.
// Формы строятся по правилам, поэтому ответ всегда верен; неправильные варианты - типичные ошибки
// (правило не той группы, не то чередование в て-форме) и другие формы того же глагола.

import { L } from '../gen.js';

/** Годан-глаголы на -iru/-eru, которые спрягаются не как итидан. */
const GODAN_RU = new Set(['帰る', '入る', '減る', '走る', '知る', '切る', '要る', '限る', '滑る', '握る', '喋る', '蹴る', '照る', '散る']);
const IE = new Set('いきしちにひみりぎじびぴえけせてねへめれげぜでべぺ');
// Последний слог годан-глагола → [а-ряд, и-ряд, э-ряд, о-ряд, て-форма].
const ROWS = {
  う: ['わ', 'い', 'え', 'お', 'って'],
  く: ['か', 'き', 'け', 'こ', 'いて'],
  ぐ: ['が', 'ぎ', 'げ', 'ご', 'いで'],
  す: ['さ', 'し', 'せ', 'そ', 'して'],
  つ: ['た', 'ち', 'て', 'と', 'って'],
  ぬ: ['な', 'に', 'ね', 'の', 'んで'],
  ぶ: ['ば', 'び', 'べ', 'ぼ', 'んで'],
  む: ['ま', 'み', 'め', 'も', 'んで'],
  る: ['ら', 'り', 'れ', 'ろ', 'って'],
};

/** Группа глагола: godan, ichidan, suru, kuru. */
export function verbClass(jp, kana) {
  if (kana.endsWith('する')) return 'suru';
  if (jp === '来る') return 'kuru';
  if (kana.endsWith('る') && IE.has(kana.at(-2)) && !GODAN_RU.has(jp)) return 'ichidan';
  return 'godan';
}

const taOf = (te) => te.replace(/て$/, 'た').replace(/で$/, 'だ');

function godan(jp) {
  const base = jp.slice(0, -1);
  const [a, i, e, o, te0] = ROWS[jp.at(-1)];
  const te = jp === '行く' ? '行って' : base + te0;
  return {
    masu: `${base}${i}ます`, masen: `${base}${i}ません`, mashita: `${base}${i}ました`, tai: `${base}${i}たい`, nagara: `${base}${i}ながら`,
    te, ta: taOf(te), tara: `${taOf(te)}ら`,
    nai: jp === 'ある' ? 'ない' : `${base}${a}ない`, nakatta: jp === 'ある' ? 'なかった' : `${base}${a}なかった`,
    pot: `${base}${e}る`, ba: `${base}${e}ば`, imp: `${base}${e}`, vol: `${base}${o}う`,
    pass: `${base}${a}れる`, caus: `${base}${a}せる`, cp: `${base}${a}せられる`,
  };
}

function ichidan(jp) {
  const s = jp.slice(0, -1);
  return {
    masu: `${s}ます`, masen: `${s}ません`, mashita: `${s}ました`, tai: `${s}たい`, nagara: `${s}ながら`,
    te: `${s}て`, ta: `${s}た`, tara: `${s}たら`, nai: `${s}ない`, nakatta: `${s}なかった`,
    pot: `${s}られる`, ba: `${s}れば`, imp: `${s}ろ`, vol: `${s}よう`, pass: `${s}られる`, caus: `${s}させる`, cp: `${s}させられる`,
  };
}

function irregular(jp, cls) {
  if (cls === 'kuru') {
    return { masu: '来ます', masen: '来ません', mashita: '来ました', tai: '来たい', nagara: '来ながら', te: '来て', ta: '来た', tara: '来たら', nai: '来ない', nakatta: '来なかった', pot: '来られる', ba: '来れば', imp: '来い', vol: '来よう', pass: '来られる', caus: '来させる', cp: '来させられる' };
  }
  const p = jp.slice(0, -2);
  return {
    masu: `${p}します`, masen: `${p}しません`, mashita: `${p}しました`, tai: `${p}したい`, nagara: `${p}しながら`,
    te: `${p}して`, ta: `${p}した`, tara: `${p}したら`, nai: `${p}しない`, nakatta: `${p}しなかった`,
    pot: `${p}できる`, ba: `${p}すれば`, imp: `${p}しろ`, vol: `${p}しよう`, pass: `${p}される`, caus: `${p}させる`, cp: `${p}させられる`,
  };
}

/** Все формы глагола. */
export function conjugate(jp, kana) {
  const cls = verbClass(jp, kana);
  return cls === 'godan' ? godan(jp) : cls === 'ichidan' ? ichidan(jp) : irregular(jp, cls);
}

/** Типичные ошибки для формы key: правило другой группы и неверные чередования. */
export function wrongForms(jp, kana, key) {
  const cls = verbClass(jp, kana);
  const out = [];
  if (jp.endsWith('る') && cls !== 'suru' && cls !== 'kuru') {
    const other = cls === 'godan' ? ichidan(jp) : godan(jp);
    // Для итидан «годан-потенциал» (食べれる) - разговорная форма, её не даём как ошибку.
    if (!(cls === 'ichidan' && key === 'pot')) out.push(other[key]);
  }
  if (cls === 'godan') {
    const base = jp.slice(0, -1);
    const [a, i, e] = ROWS[jp.at(-1)];
    const te = [`${base}${i}て`, `${base}って`, `${base}んで`, `${base}いて`, `${base}して`];
    const map = {
      te, ta: te.map(taOf), tara: te.map((x) => `${taOf(x)}ら`),
      masu: [`${base}${a}ます`, `${base}${e}ます`], masen: [`${base}${a}ません`], mashita: [`${base}${a}ました`],
      nai: [`${base}${i}ない`, `${base}${e}ない`], nakatta: [`${base}${i}なかった`], tai: [`${base}${a}たい`, `${jp}たい`],
      pot: [`${base}${a}れる`, `${base}${i}れる`], ba: [`${base}${a}ば`, `${jp}れば`], vol: [`${base}${a}う`, `${base}${a}よう`],
      imp: [`${base}${i}`, `${jp}ろ`], pass: [`${base}${e}れる`, `${base}${i}れる`], caus: [`${base}${e}せる`, `${base}${i}せる`],
      cp: [`${base}${e}させられる`, `${base}${a}させれる`], nagara: [`${base}${a}ながら`, `${jp}ながら`],
    };
    out.push(...(map[key] ?? []));
  } else if (cls === 'ichidan') {
    const s = jp.slice(0, -1);
    const map = {
      te: [`${s}って`, `${s}んで`, `${s}いて`], ta: [`${s}った`, `${s}んだ`], tara: [`${s}ったら`],
      masu: [`${s}ります`, `${jp}ます`], masen: [`${s}りません`], mashita: [`${s}りました`], nai: [`${s}らない`, `${jp}ない`], nakatta: [`${s}らなかった`],
      tai: [`${s}りたい`, `${jp}たい`], pot: [`${s}させる`, `${s}られれる`], ba: [`${s}ば`, `${s}らば`], vol: [`${s}ろう`, `${s}おう`], imp: [`${s}れ`, `${s}い`],
      pass: [`${s}れる`, `${s}られれる`], caus: [`${s}せる`, `${s}らせる`], cp: [`${s}させれる`, `${s}せられる`], nagara: [`${s}りながら`],
    };
    out.push(...(map[key] ?? []));
  } else {
    const p = cls === 'suru' ? jp.slice(0, -2) : '来';
    const s = cls === 'suru' ? `${p}す` : '来';
    const map = {
      te: [`${s}って`, `${s}いて`], ta: [`${s}った`], tara: [`${s}ったら`], masu: [`${s}ります`, `${p}さます`], masen: [`${s}りません`], mashita: [`${s}りました`],
      nai: [`${s}らない`, `${p}さない`], nakatta: [`${s}らなかった`], tai: [`${s}りたい`], pot: [`${p}しれる`, `${p}られれる`], ba: [`${p}しれば`, `${s}ば`],
      vol: [`${s}ろう`, `${p}さよう`], imp: [`${s}れ`, `${p}せ`], pass: [`${p}しられる`, `${p}さられる`], caus: [`${p}しさせる`, `${p}させれる`], cp: [`${p}しさせられる`], nagara: [`${s}りながら`],
    };
    out.push(...(map[key] ?? []));
  }
  return out;
}

