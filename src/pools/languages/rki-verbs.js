const rot = (arr, k) => arr.map((_, i) => arr[(i + k) % arr.length]);
function three(ok, cands) {
  const out = [];
  for (const c of cands) if (c && c !== ok && !out.includes(c) && out.length < 3) out.push(c);
  return out.length === 3 ? out : null;
}
function row(level, sentence, ok, cands, ex) {
  const wrong = three(ok, cands);
  return wrong ? [level, sentence, ok, wrong, ex] : null;
}
const full = (s, ok) => s.replace(/______( \([^)]*\))?/, ok);

/** Задание «форма для лица»: неверные - формы того же глагола для других лиц. */
function personRow(level, sentence, forms, p, inf, tense) {
  const ok = forms[p];
  return row(level, sentence, ok, rot(forms, p + 1), L(
    `${inf}, ${tense.en}: the form for ${PERS[p].en} is ${ok}. «${full(sentence, ok)}»`,
    `${inf}, ${tense.ru}: для лица «${PERS[p].ru}» - ${ok}. «${full(sentence, ok)}»`,
    `${inf}, ${tense.kk}: ${PERS[p].kk} үшін - ${ok}. «${full(sentence, ok)}»`,
  ));
}
